class AriaDiffTest(unittest.TestCase):
    def test_diff_reports_each_capture_key_and_only_changed_lines(self) -> None:
        before = {"records": [
            record("V-0", "desktop", 0, aria_snapshot="- main\n- heading \"A\""),
            record("V-0", "mobile", 0, aria_snapshot="- main"),
            record("V-0", "desktop", 1, aria_snapshot="- dialog"),
        ]}
        after = {"records": [
            record("V-0", "desktop", 0, aria_snapshot="- main\n- heading \"B\""),
            record("V-0", "mobile", 0, aria_snapshot="- main"),
            record("V-0", "mobile", 1, aria_snapshot="- banner"),
        ]}
        diffs = aria_diff(before, after)

        self.assertEqual(
            [(item["view_id"], item["step"], item["viewport_id"], item["status"]) for item in diffs],
            [("V-0", 0, "desktop", "changed"), ("V-0", 0, "mobile", "unchanged"),
             ("V-0", 1, "desktop", "removed"), ("V-0", 1, "mobile", "added")],
        )
        self.assertEqual(diffs[0]["diff"], ['-- heading "A"', '+- heading "B"'])
        self.assertEqual(diffs, aria_diff(before, after))


